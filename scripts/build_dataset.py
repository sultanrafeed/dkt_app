"""Build the app dataset from the extracted PDF data.

Inputs (generated by the extract_* scripts, never hand-edited):
  data/questions.raw.json   - every question/option/official answer from the DKT PDF
  data/handbook.json        - structured Road User Handbook
Hand-maintained input:
  data/review-notes.json    - questions whose source content needs a manual check

Outputs:
  public/data/questions.json, public/data/handbook.json
  data/extraction-report.md, data/extraction-report.json

Validation failures stop the build (exit code 1).

Usage: python3 scripts/build_dataset.py
"""
import json, math, os, re, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = lambda *p: os.path.join(ROOT, *p)

STOP = set("""a an the and or of to in on at for by is are be you your it its if as with
this that these those from not no yes must should can may do does what which when where who
how will would there their they them he she his her than then so only any all at vehicle
vehicles driver drivers driving drive road car cars""".split())

# Keyword rules that tie a question to a handbook section. They only choose which
# handbook pages to suggest for reading; they never touch question or answer text.
TOPIC_RULES = [
    (r"roundabout", "Roundabouts"),
    (r"railway|level crossing|train|boom ?gate", "Railway level crossings"),
    (r"pedestrian crossing|zig-zag|pelican|children'?s crossing|school crossing supervisor", "Pedestrian crossings"),
    (r"pedestrian|people on the road|person crossing|older people", "Pedestrians"),
    (r"bicycle|cyclist", "Bicycle riders"),
    (r"motorcycl", "Motorcycle riders"),
    (r"horse", "Horse riders"),
    (r"light rail|tram", "Tramways and tram lanes"),
    (r"traffic light|red light|green light|yellow|amber|arrow shows|green arrow|red arrow", "Traffic lights"),
    (r"give way sign|give way line", "Give way signs and give way lines"),
    (r"stop sign|stop line", "Stop signs and stop lines"),
    (r"t-intersection|intersection", "Intersections"),
    (r"u-turn|u turn", "U-turns and three-point turns"),
    (r"indicat|signal (your|the|with)|hand signal|turn signals", "Indicating"),
    (r"turn right|turn left|right-hand turn|left turn|right turn", "Turning left and right"),
    (r"one way", "One-way streets"),
    (r"overtak|being overtaken|pass(ing)? (a|the|another)", "Overtaking"),
    (r"merg|change lanes|changing lanes|lane line", "Merging and changing lanes"),
    (r"freeway|motorway", "Motorways and freeways"),
    (r"dividing line|unbroken|double (unbroken|lines)|edge line|broken yellow|centre line", "Road lines and markings"),
    (r"transit lane|t2|t3", "Transit lanes"),
    (r"bus lane", "Bus lanes"),
    (r"median turning lane", "Median turning lanes"),
    (r"park|double-park|double park|clearway|no stopping|taxi zone|kerb", "No parking"),
    (r"angle park|parallel", "Ways to park"),
    (r"speed limit|km/h|school zone|shared (traffic )?zone|local traffic", "Speed limits"),
    (r"alcohol|drink|bac|breath test", "Alcohol limits"),
    (r"drug|medicine|medication|tablets", "Drugs and medicines"),
    (r"seat ?belt", "Seatbelts"),
    (r"child restraint|baby|capsule|child seat", "Child car seats (child restraint)"),
    (r"mobile phone", "Mobile phones"),
    (r"tired|sleepy|fatigue|long trip|long drive|rest", "Fatigue"),
    (r"following distance|gap|seconds behind|three seconds", "Safe stopping distance"),
    (r"scan", "Safe stopping distance"),
    (r"wet|rain|fog|slippery|gravel", "Driving in poor conditions"),
    (r"headlight|high beam|low beam|dazzle|hazard warning lights|lights on", "Lights and horns"),
    (r"horn", "Lights and horns"),
    (r"ambulance|siren|emergency vehicle|fire truck|police officers", "Police and emergency vehicles"),
    (r"road ?works|traffic controller|road work", "Roadworks"),
    (r"accident|crash", "Crashes"),
    (r"tow|trailer|caravan", "Towing"),
    (r"tyre|defect notice|noisy|smoke", "Roadworthiness"),
    (r"registration", "Vehicle registration"),
    (r"number plate", "Number plates"),
    (r"seat puts you|driver's seat", "Driving posture"),
    (r"licence|l or p plates|p1|p2|learner", "Licence restrictions"),
    (r"demerit", "Demerit points"),
    (r"street or drag racing|drag racing", "Hooning and street racing"),
    (r"dangerous driving|negligent", "Negligent or dangerous driving"),
    (r"medical condition", "Medical conditions and disability"),
    (r"bus|truck|long vehicle", "Trucks and buses"),
    (r"narrow|bridge", "Narrow bridges and roads"),
    (r"farm animals|kangaroo|animals|stock", "Wildlife and livestock"),
]
# Used only when no rule above matched
FALLBACK_RULES = [(r"sign", "Warning signs")]


def tokens(s):
    return [w for w in re.findall(r"[a-z0-9]+", s.lower()) if w not in STOP and len(w) > 2]


def main():
    raw = json.load(open(D("data", "questions.raw.json")))
    hb = json.load(open(D("data", "handbook.json")))
    notes = json.load(open(D("data", "review-notes.json")))
    errors, normalisations = [], []

    # ---- handbook sections as learning topics -------------------------------------
    pages_by_pdf = {p["pdfPage"]: p for p in hb["pages"]}
    sections = []
    for i, t in enumerate(hb["toc"]):
        text = []
        started = False
        for pno in range(t["startPdfPage"], t["endPdfPage"] + 1):
            for b in pages_by_pdf[pno]["blocks"]:
                if b["type"] == "h2":
                    if b["text"] == t["section"] and pno == t["startPdfPage"]:
                        started = True
                        continue
                    if started:
                        break
                if started or pno > t["startPdfPage"]:
                    started = True
                    text.append(b["text"])
        sections.append(dict(id=re.sub(r"[^a-z0-9]+", "-", t["section"].lower()).strip("-"),
                             part=t["part"], title=t["section"],
                             startPage=t["startPdfPage"] - hb["pageOffset"],
                             endPage=t["endPdfPage"] - hb["pageOffset"],
                             startPdfPage=t["startPdfPage"], endPdfPage=t["endPdfPage"],
                             text=" ".join(text)))
    by_title = {s["title"]: s for s in sections}
    for _, title in TOPIC_RULES:
        if title not in by_title:
            errors.append(f"Topic rule points at unknown handbook section '{title}'")

    # TF-IDF over handbook sections, used when keyword rules find nothing
    docs = [collections.Counter(tokens(s["title"] + " " + s["text"])) for s in sections]
    df = collections.Counter(w for d in docs for w in d)
    N = len(docs)
    idf = {w: math.log(N / (1 + c)) + 1 for w, c in df.items()}
    vecs = []
    for d in docs:
        v = {w: (1 + math.log(c)) * idf[w] for w, c in d.items()}
        n = math.sqrt(sum(x * x for x in v.values())) or 1
        vecs.append({w: x / n for w, x in v.items()})

    def tfidf_best(text, k=2):
        q = collections.Counter(tokens(text))
        v = {w: (1 + math.log(c)) * idf.get(w, 0) for w, c in q.items()}
        n = math.sqrt(sum(x * x for x in v.values())) or 1
        scores = [(sum(v.get(w, 0) / n * x for w, x in sv.items()), s["title"]) for sv, s in zip(vecs, sections)]
        scores.sort(reverse=True)
        return [t for sc, t in scores[:k] if sc > 0.08]

    # ---- questions ----------------------------------------------------------------
    questions, seen = [], set()
    for q in raw:
        cat = re.sub(r"\s*RUH\d*$", "", q["category"]).strip()
        if cat != q["category"]:
            normalisations.append(f"{q['code']}: category label '{q['category']}' -> '{cat}' (stray 'RUH' reference marker removed)")
        opts = []
        for o in q["options"]:
            o2 = re.sub(r"^\.\s*", "", o).strip()
            if o2 != o:
                normalisations.append(f"{q['code']}: leading '.' removed from option '{o[:40]}'")
            opts.append(o2)
        text = q["question"]
        full = (text + " " + opts[q["correctIndex"]] if q["correctIndex"] is not None else text).lower()
        topics = []
        for pat, title in TOPIC_RULES:
            if re.search(pat, full) and title not in topics:
                topics.append(title)
        topics = topics[:3]
        if not topics:
            topics = [t for pat, t in FALLBACK_RULES if re.search(pat, full)] or tfidf_best(full)
        img = None
        if q["image"]:
            img = dict(src=q["image"]["file"], width=q["image"]["width"], height=q["image"]["height"],
                       alt=f"Picture from question {q['code']} in the NSW DKT question document (page {q['image']['page']})"
                           + (f"; labels shown: {', '.join(q['imageLabels'])}" if q["imageLabels"] else ""))
        rn = notes.get(q["code"])
        item = dict(
            id=q["code"], code=q["code"], category=cat, section=q["section"], prefix=q["prefix"],
            question=text, options=opts, correctIndex=q["correctIndex"],
            source=dict(document="Driver Knowledge Test Questions – Class C (Car) Licence", page=q["sourcePage"],
                        answerEvidence="Correct option is set in bold in the source PDF"),
            image=img,
            topics=[dict(id=by_title[t]["id"], title=t, startPage=by_title[t]["startPage"], endPage=by_title[t]["endPage"])
                    for t in topics],
            review=rn,
        )
        # ---- validation --------------------------------------------------------
        if item["id"] in seen: errors.append(f"Duplicate id {item['id']}")
        seen.add(item["id"])
        if not text.strip(): errors.append(f"{item['id']}: empty question")
        if len(opts) < 2: errors.append(f"{item['id']}: fewer than 2 options")
        if any(not o.strip() for o in opts): errors.append(f"{item['id']}: empty option")
        if len(set(o.lower() for o in opts)) != len(opts): errors.append(f"{item['id']}: duplicate options")
        if q["boldOptionCount"] != 1 or item["correctIndex"] is None:
            errors.append(f"{item['id']}: expected exactly one bold (correct) option, found {q['boldOptionCount']}")
        if img and not os.path.exists(D("public", img["src"])): errors.append(f"{item['id']}: image file missing")
        questions.append(item)

    # Questions whose wording points at a picture must have one
    visual = re.compile(r"this sign|these lights|this light|diagram|shown|marked [A-Z]\b|car [A-Z]\b|vehicle [A-Z]\b|picture|these markings|this intersection|this roundabout|these people|this person", re.I)
    for q in questions:
        if visual.search(q["question"]) and not q["image"]:
            errors.append(f"{q['id']}: question refers to a picture but none was extracted")

    # Gaps in numbering are expected (the published bank skips retired numbers); report them.
    gaps = {}
    for p in sorted({q["prefix"] for q in questions}):
        nums = sorted(int(re.sub(r"\D", "", q["code"])) for q in questions if q["prefix"] == p)
        gaps[p] = dict(count=len(nums), first=nums[0], last=nums[-1],
                       missingNumbers=[n for n in range(nums[0], nums[-1] + 1) if n not in nums])

    for code in notes:
        if code not in seen: errors.append(f"review-notes.json references unknown question {code}")

    # ---- write outputs --------------------------------------------------------------
    os.makedirs(D("public", "data"), exist_ok=True)
    categories = []
    for q in questions:
        if q["category"] not in categories: categories.append(q["category"])
    meta = dict(
        questionSource="Driver Knowledge Test Questions – Class C (Car) Licence (Roads and Maritime Services PDF, created 2018-09-13)",
        handbookSource=hb["source"],
        total=len(questions), categories=categories,
        sections=list(dict.fromkeys(q["section"] for q in questions)),
    )
    json.dump(dict(meta=meta, questions=questions), open(D("public", "data", "questions.json"), "w"), ensure_ascii=False, separators=(",", ":"))
    hb_out = dict(source=hb["source"], pageOffset=hb["pageOffset"],
                  sections=[{k: v for k, v in s.items() if k != "text"} for s in sections],
                  pages=[dict(pdfPage=p["pdfPage"], page=p["page"], section=p["section"], part=p["part"],
                              image=p["image"], blocks=p["blocks"]) for p in hb["pages"]])
    json.dump(hb_out, open(D("public", "data", "handbook.json"), "w"), ensure_ascii=False, separators=(",", ":"))

    with_img = [q for q in questions if q["image"]]
    report = dict(
        totalSourceQuestionHeaders=len(raw), successfullyImported=len(questions),
        questionsWithImages=len(with_img), questionsWithoutImages=len(questions) - len(with_img),
        questionsRequiringManualReview=sorted(notes.keys()),
        byCategory=dict(collections.Counter(q["category"] for q in questions)),
        bySection=dict(collections.Counter(q["section"] for q in questions)),
        numbering=gaps, normalisations=normalisations, errors=errors,
        handbookPages=len(hb["pages"]), handbookSections=len(sections),
    )
    json.dump(report, open(D("data", "extraction-report.json"), "w"), indent=1, ensure_ascii=False)
    md = ["# Extraction report", "",
          "Generated by `scripts/build_dataset.py` from the two supplied PDFs.", "",
          "```text",
          f"Total source questions:           {len(raw)}",
          f"Successfully imported:            {len(questions)}",
          f"Questions with images:            {len(with_img)}",
          f"Questions without images:         {len(questions) - len(with_img)}",
          f"Questions requiring manual review: {len(notes)}",
          f"Missing/uncertain data:           {len(errors)} validation errors",
          "```", "",
          "## How the data was extracted", "",
          "- **Questions, options:** text read from every page of `driver-knowledge-test-questions-car.pdf` (94 pages), keeping page breaks together.",
          "- **Official answer:** the source PDF prints the correct option in a bold font (Arial-Black or Arial-BoldMT); distractors are regular weight. Every question has exactly one bold option. The answer is never inferred from position.",
          "- **Images:** every embedded picture and vector drawing between one question heading and the next is cropped from the page at 180 dpi, with the question text removed. Labels printed on the picture (letters such as A, B, M, N, O) are kept. All 193 embedded pictures in the PDF are assigned to exactly one question; one sign (LD033) is vector artwork and is also captured.",
          f"- **Handbook:** all {len(hb['pages'])} pages of `Road-User-Handbook-English.pdf` were read into {len(sections)} sections using the handbook's own heading styles. Each page is also rendered as an image, because most handbook diagrams and signs are vector artwork.",
          "- **Handbook links on questions:** chosen automatically by keyword rules (and a text-similarity fallback). They point to relevant reading; they do not change any question or answer.",
          "",
          "## Questions by source category", "",
          "| Category | Questions |", "|---|---|"]
    md += [f"| {k} | {v} |" for k, v in report["byCategory"].items()]
    md += ["", "## Numbering gaps", "",
           "The source bank skips numbers (retired questions are not printed). These numbers do not appear anywhere in the PDF, so nothing is missing from the extraction:", ""]
    md += [f"- **{p}** ({g['count']} questions, {p}{g['first']}–{p}{g['last']}): {len(g['missingNumbers'])} unused numbers" for p, g in gaps.items()]
    md += ["", "## Text normalisations", "", "Only formatting artefacts were changed:", ""]
    md += [f"- {n}" for n in normalisations] or ["- none"]
    md += ["", "## Questions requiring manual review", "",
           "The official answer is kept exactly as printed. These notes flag where the 2018 question document and the February 2026 handbook differ, or where the handbook does not cover the point.", ""]
    md += [f"- **{c}** – {n['note']}" for c, n in sorted(notes.items())]
    md += ["", "## Validation", ""]
    md += [f"- ❌ {e}" for e in errors] or ["- ✅ All checks passed: unique IDs, non-empty questions and options, exactly one official answer per question, every picture-referencing question has an image, every image file exists."]
    open(D("data", "extraction-report.md"), "w").write("\n".join(md) + "\n")

    print(f"{len(questions)} questions, {len(with_img)} with images, {len(sections)} handbook sections")
    if errors:
        print("\n".join(errors)); sys.exit(1)


if __name__ == "__main__":
    main()
